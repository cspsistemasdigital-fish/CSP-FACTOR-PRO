-- Perfis: cada usuario le o proprio; ADMIN le e administra perfis. Papel nao e autoatribuivel.
drop policy if exists profiles_read_self_or_admin on public.profiles;
create policy profiles_read_self_or_admin on public.profiles
for select to authenticated
using (id = (select auth.uid()) or public.factorpro_has_role(array['ADMIN']));

drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles
for update to authenticated
using (public.factorpro_has_role(array['ADMIN']))
with check (public.factorpro_has_role(array['ADMIN']));

-- Clientes: ADMIN e OPERATOR escrevem; somente ADMIN pode marcar exclusao logica.
drop policy if exists clients_read on public.clients;
create policy clients_read on public.clients for select to authenticated
using (public.factorpro_is_active() and is_deleted = false);
drop policy if exists clients_insert on public.clients;
create policy clients_insert on public.clients for insert to authenticated
with check (
    public.factorpro_has_role(array['ADMIN', 'OPERATOR'])
    and created_by_id = (select auth.uid())
);
drop policy if exists clients_update on public.clients;
create policy clients_update on public.clients for update to authenticated
using (public.factorpro_has_role(array['ADMIN']) or
       (public.factorpro_has_role(array['OPERATOR']) and is_deleted = false))
with check (public.factorpro_has_role(array['ADMIN']) or
            (public.factorpro_has_role(array['OPERATOR']) and is_deleted = false));

