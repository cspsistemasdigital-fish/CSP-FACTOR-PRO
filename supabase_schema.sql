create or replace function public.factorpro_audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    old_row jsonb;
    new_row jsonb;
    row_id bigint;
    action_name varchar(30);
begin
    if tg_op = 'INSERT' then
        new_row := to_jsonb(new);
        row_id := nullif(new_row ->> 'id', '')::bigint;
        action_name := 'CREATE';
    elsif tg_op = 'UPDATE' then
        old_row := to_jsonb(old);
        new_row := to_jsonb(new);
        row_id := nullif(new_row ->> 'id', '')::bigint;
        if old_row ->> 'is_deleted' = 'false' and new_row ->> 'is_deleted' = 'true' then
            action_name := 'DELETE';
        else
            action_name := 'UPDATE';
        end if;
    else
        old_row := to_jsonb(old);
        row_id := nullif(old_row ->> 'id', '')::bigint;
        action_name := 'DELETE';
    end if;

    insert into public.audit_logs (
        user_id, user_email, action, entity, entity_id, description, changes
    )
    values (
        (select auth.uid()),
        (select auth.jwt() ->> 'email'),
        action_name,
        tg_table_name,
        row_id,
        tg_table_name || ' ' || lower(action_name),
        jsonb_build_object('before', old_row, 'after', new_row)
    );

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

revoke all on function public.factorpro_audit_row_change() from public, anon;
grant execute on function public.factorpro_audit_row_change() to authenticated;

