create or replace function public.factorpro_limit_report_filters()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
    active_count integer;
begin
    if new.is_deleted = false then
        perform pg_advisory_xact_lock(hashtext(new.user_id::text));
        select count(*) into active_count
        from public.report_filters
        where user_id = new.user_id
          and is_deleted = false
          and id <> coalesce(new.id, -1);
        if active_count >= 20 then
            raise exception 'Limite de 20 filtros salvos ativos por usuario atingido'
                using errcode = '23514';
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists factorpro_report_filter_limit on public.report_filters;
create trigger factorpro_report_filter_limit
before insert or update on public.report_filters
for each row execute function public.factorpro_limit_report_filters();

