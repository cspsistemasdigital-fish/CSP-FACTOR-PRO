    on public.profiles (lower(email));

-- Helpers usados pelas politicas RLS. SECURITY DEFINER evita recursao ao consultar profiles.
create or replace function public.factorpro_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
    select p.role
    from public.profiles as p
    where p.id = (select auth.uid())
      and p.is_active = true
    limit 1
$$;

create or replace function public.factorpro_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select public.factorpro_role() is not null
$$;

create or replace function public.factorpro_has_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select coalesce(public.factorpro_role() = any (allowed_roles), false)
$$;

revoke all on function public.factorpro_role() from public, anon;
revoke all on function public.factorpro_is_active() from public, anon;
revoke all on function public.factorpro_has_role(text[]) from public, anon;
grant execute on function public.factorpro_role() to authenticated;
grant execute on function public.factorpro_is_active() to authenticated;
grant execute on function public.factorpro_has_role(text[]) to authenticated;

-- Criacao de perfil inativo para novas contas. O papel ADMIN deve ser atribuido
-- manualmente pelo proprietario no SQL Editor, nunca por metadata enviada pelo cliente.
create or replace function public.factorpro_create_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.profiles (id, name, email, role, is_active)
    values (
        new.id,
        coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)),
        lower(new.email),
        'VIEWER',
        false
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

revoke all on function public.factorpro_create_profile() from public, anon, authenticated;
drop trigger if exists factorpro_auth_user_created on auth.users;
create trigger factorpro_auth_user_created
after insert on auth.users
for each row execute function public.factorpro_create_profile();

