do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'clients', 'operations', 'cheques', 'boletos', 'receipts', 'loans',
        'installments', 'document_attachments', 'agenda_events', 'report_filters', 'settings'
    ]
    loop
        execute format('drop trigger if exists factorpro_set_updated_at on public.%I', table_name);
        execute format(
            'create trigger factorpro_set_updated_at before update on public.%I for each row execute function public.factorpro_set_updated_at()',
            table_name
        );
        execute format('drop trigger if exists factorpro_set_updated_by on public.%I', table_name);
        execute format(
            'create trigger factorpro_set_updated_by before update on public.%I for each row execute function public.factorpro_set_updated_by()',
            table_name
        );
    end loop;
end;
$$;

do $$
declare
